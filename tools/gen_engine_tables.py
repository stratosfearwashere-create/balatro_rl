"""Write balatro_rl/sim/cpp/engine/tables_gen.hpp from the Python definitions (jokers, consumables, vouchers,
packs, tags, bosses, blind sizes, the item vocabulary), so the C++ engine's tables cannot drift from them.

    python tools/gen_engine_tables.py            # rewrite the header
    python tools/gen_engine_tables.py --check    # exit 1 if the header on disk is out of date
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)
OUT = os.path.join(ROOT, "balatro_rl", "sim", "cpp", "engine", "tables_gen.hpp")

HOOKS = ("before", "card", "retrig", "held", "main", "after", "discard", "end_round", "init", "blind_select", "on_sell")


def ident(s: str) -> str:
    return s.upper().replace("-", "_")


def cbool(x) -> str:
    return "true" if x else "false"


def generate() -> str:
    from balatro_rl.sim.jokers import JOKERS, JOKER_KEYS, NOT_IN_POOL, EDITION_COST
    from balatro_rl.sim.items import (PLANETS, TAROTS, TAROT_ENH, TAROT_SUIT, SPECTRALS, HIDDEN_SPECTRALS, VOUCHERS,
                                      VOUCHER_COST, PACKS, PACK_KEYS, TAGS, TAG_MIN_ANTE, DECKS, ALL_BOSSES, BOSSES,
                                      SUIT_BOSS, BLIND_BASE, STAKES, VOCAB, item_id)
    from balatro_rl.sim.hands import HAND_BASE, N_HANDS
    from balatro_rl.sim.cards import ENHANCEMENTS, EDITIONS
    from balatro_rl.sim.game import TARGETED
    L = ["// GENERATED by tools/gen_engine_tables.py from the Python definitions. Do not edit.",
         "#pragma once", "#include <cstdint>", "", "namespace bal {", ""]
    # ---- jokers (definition order: the order pools are built in)
    keys = list(JOKERS)
    L.append("enum JokerId : int16_t {")
    L += [f"    J_{ident(k)} = {i}," for i, k in enumerate(keys)]
    L += [f"    J_COUNT = {len(keys)}", "};", ""]
    L.append("enum HookBit : uint16_t { " + ", ".join(f"H_{ident(h)} = {1 << i}" for i, h in enumerate(HOOKS)) + " };")
    L.append("struct JokerDef { const char* key; int8_t rarity; int8_t cost; bool eternal_ok, perish_ok, copyable, "
             "not_in_pool; uint16_t hooks; int16_t sorted_rank; int16_t vocab; };")
    L.append("static const JokerDef JOKER_DEFS[J_COUNT] = {")
    for k in keys:
        d = JOKERS[k]
        bits = sum(1 << i for i, h in enumerate(HOOKS) if getattr(d, h) is not None)
        L.append(f'    {{"{k}", {d.rarity}, {d.cost}, {cbool(d.eternal_ok)}, {cbool(d.perish_ok)}, '
                 f'{cbool(d.copyable)}, {cbool(k in NOT_IN_POOL)}, {bits}, {JOKER_KEYS.index(k)}, '
                 f'{item_id("j_" + k)}}},')
    L += ["};", f"static const int VOCAB_J_UNKNOWN = {item_id('j_unknown')};",
          f"static const int VOCAB_PLAYING_CARD = {item_id('<playing_card>')};", ""]
    # joker ids in alphabetical order of their keys (sorted(joker_pool))
    L.append("static const int16_t JOKERS_SORTED[J_COUNT] = {" + ", ".join(str(keys.index(k)) for k in JOKER_KEYS) + "};")
    L.append("static const int EDITION_COST[5] = {" + ", ".join(str(EDITION_COST[e]) for e in EDITIONS) + "};")
    L.append("")
    # ---- consumables: planets, tarots, spectrals in their dict orders
    cons = [("planet", p) for p in PLANETS] + [("tarot", t) for t in TAROTS] + [("spectral", s) for s in SPECTRALS]
    L.append("enum ConsId : int8_t {")
    L.append("    C_NONE = -1,")
    L += [f"    C_{ident(n)} = {i}," for i, (_, n) in enumerate(cons)]
    L += [f"    C_COUNT = {len(cons)}", "};"]
    L.append(f"static const int N_PLANETS = {len(PLANETS)}, N_TAROTS = {len(TAROTS)}, N_SPECTRALS = {len(SPECTRALS)};")
    L.append("enum ConsKind : int8_t { CK_PLANET = 0, CK_TAROT = 1, CK_SPECTRAL = 2 };")
    L.append("struct ConsDef { const char* name; int8_t kind; int8_t need; int8_t planet_hand; int8_t enh; int8_t suit; "
             "bool targeted; bool hidden; int16_t vocab; };")
    L.append("static const ConsDef CONS_DEFS[C_COUNT] = {")
    for kind, n in cons:
        need = TAROTS.get(n, 0) if kind == "tarot" else SPECTRALS.get(n, 0) if kind == "spectral" else 0
        hand = PLANETS.get(n, -1) if kind == "planet" else -1
        enh = ENHANCEMENTS.index(TAROT_ENH[n]) if n in TAROT_ENH else -1
        suit = TAROT_SUIT.get(n, -1)
        L.append(f'    {{"{n}", {["planet", "tarot", "spectral"].index(kind)}, {need}, {hand}, {enh}, {suit}, '
                 f'{cbool(n in TARGETED)}, {cbool(n in HIDDEN_SPECTRALS)}, {item_id("c_" + n)}}},')
    L += ["};", ""]
    hp = {h: p for p, h in PLANETS.items()}
    L.append("static const int8_t HAND_TO_PLANET[12] = {" + ", ".join(f"C_{ident(hp[h])}" for h in range(N_HANDS)) + "};")
    L.append("static const int HAND_BASE[12][4] = {" + ", ".join("{" + ", ".join(map(str, HAND_BASE[h])) + "}" for h in range(N_HANDS)) + "};")
    L.append("")
    # ---- vouchers
    vk = list(VOUCHERS)
    L.append("enum VoucherId : int8_t {")
    L += [f"    V_{ident(v)} = {i}," for i, v in enumerate(vk)]
    L += [f"    V_COUNT = {len(vk)}", "};"]
    L.append("struct VoucherDef { const char* key; int8_t prereq; int16_t vocab; };")
    L.append("static const VoucherDef VOUCHER_DEFS[V_COUNT] = {")
    L += [f'    {{"{v}", {vk.index(VOUCHERS[v]) if VOUCHERS[v] else -1}, {item_id("v_" + v)}}},' for v in vk]
    L += ["};", f"static const int VOUCHER_COST = {VOUCHER_COST};", ""]
    # ---- packs
    kinds = ["arcana", "celestial", "standard", "buffoon", "spectral"]
    sizes = ["normal", "jumbo", "mega"]
    L.append("enum PackKind : int8_t { PK_NONE = -1, PK_ARCANA = 0, PK_CELESTIAL, PK_STANDARD, PK_BUFFOON, PK_SPECTRAL };")
    L.append("enum PackSize : int8_t { PS_NORMAL = 0, PS_JUMBO, PS_MEGA };")
    L.append("static const char* const PACK_KIND_KEYS[5] = {" + ", ".join(f'"{k}"' for k in kinds) + "};")
    L.append("struct PackDef { const char* key; int8_t kind, size, shown, picks, cost; double weight; int16_t vocab; };")
    L.append(f"static const int N_PACKS = {len(PACK_KEYS)};")
    L.append("static const PackDef PACK_DEFS[N_PACKS] = {")
    for (k, s) in PACK_KEYS:
        shown, picks, cost, w = PACKS[(k, s)]
        L.append(f'    {{"p_{k}_{s}", {kinds.index(k)}, {sizes.index(s)}, {shown}, {picks}, {cost}, {w!r}, {item_id(f"p_{k}_{s}")}}},')
    L += ["};", ""]
    # ---- tags
    L.append("enum TagId : int8_t {")
    L += [f"    T_{ident(t)} = {i}," for i, t in enumerate(TAGS)]
    L += [f"    T_COUNT = {len(TAGS)}", "};"]
    L.append("static const char* const TAG_KEYS[T_COUNT] = {" + ", ".join(f'"{t}"' for t in TAGS) + "};")
    L.append("static const int8_t TAG_MIN_ANTE[T_COUNT] = {" + ", ".join(str(TAG_MIN_ANTE.get(t, 1)) for t in TAGS) + "};")
    L.append("")
    # ---- decks, stakes
    L.append("enum DeckId : int8_t { " + ", ".join(f"D_{d} = {i}" for i, d in enumerate(DECKS)) + f", D_COUNT = {len(DECKS)} }};")
    L.append("static const char* const DECK_KEYS[D_COUNT] = {" + ", ".join(f'"{d}"' for d in DECKS) + "};")
    L.append("static const char* const STAKE_KEYS[8] = {" + ", ".join(f'"{s}"' for s in STAKES) + "};")
    L.append("")
    # ---- bosses (BOSSES then FINISHERS: the order of BOSS_KEYS)
    bk = list(ALL_BOSSES)
    L.append("enum BossId : int8_t {")
    L.append("    B_NONE = -1,")
    L += [f"    B_{ident(b)} = {i}," for i, b in enumerate(bk)]
    L += [f"    B_COUNT = {len(bk)}", "};"]
    L.append(f"static const int N_NORMAL_BOSSES = {len(BOSSES)};")
    L.append("struct BossDef { const char* key; int8_t min_ante; int8_t mult; int8_t suit; };")
    L.append("static const BossDef BOSS_DEFS[B_COUNT] = {")
    L += [f'    {{"{b}", {ALL_BOSSES[b][1]}, {ALL_BOSSES[b][2]}, {SUIT_BOSS.get(b, -1)}}},' for b in bk]
    L += ["};", ""]
    L.append("static const int BLIND_BASE[3][8] = {" + ", ".join("{" + ", ".join(map(str, BLIND_BASE[s])) + "}" for s in (1, 2, 3)) + "};")
    L.append(f"static const int VOCAB_SIZE = {len(VOCAB)};")
    L += ["", "}  // namespace bal", ""]
    return "\n".join(L)


def main():
    text = generate()
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if old != text:
            print("tables_gen.hpp is out of date: run python tools/gen_engine_tables.py")
            sys.exit(1)
        print("tables_gen.hpp is up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    main()
